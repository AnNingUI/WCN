    if (k_font_lato_regular_data != NULL && sizeof(k_font_lato_regular_data) > 0) {
        fprintf(stderr, "Loading embedded font... ");
        fflush(stderr);
        font_ready = fs_core_load_font_memory(
            core, (const uint8_t*)k_font_lato_regular_data, sizeof(k_font_lato_regular_data));
        fprintf(stderr, "%s (%zu bytes)\n", font_ready ? "OK" : "FAIL", sizeof(k_font_lato_regular_data));
        if (!font_ready) {
            fprintf(stderr, "  font-backend: %s\n", fs_core_get_font_backend_name(core));
        }
    }
    /* Fallback: try file paths */
    if (!font_ready) {
        const char* fonts[] = {
            "assets/NotoSerifSC-VF.ttf",
            "../assets/NotoSerifSC-VF.ttf",
            "../../assets/NotoSerifSC-VF.ttf",
            "assets/NotoSerif-Medium.ttf",
            "../assets/NotoSerif-Medium.ttf",
            ".lookme/use.gpu/public/fonts/Lato-Regular.ttf",
            "../.lookme/use.gpu/public/fonts/Lato-Regular.ttf",
        };
        for (size_t i = 0; i < ARRAY_COUNT(fonts); i++) {
            if (fs_core_load_font_file(core, fonts[i])) {
                font_ready = true;
                printf("Font: %s\n", fonts[i]);
                break;
            }
        }
    }
    if (!font_ready) fprintf(stderr, "Warning: no font loaded\n");

