/* ═══════════════════════════════════════════════════════════════════════════
   Text measurement bridge — Clay → WCN
   ═══════════════════════════════════════════════════════════════════════════ */

static FS_Core* g_measure_core = NULL;

static Clay_Dimensions fsclay_measure_text(
    Clay_StringSlice text,
    Clay_TextElementConfig* config,
    void* userData
) {
    (void)userData;
    if (!g_measure_core || !text.chars || text.length <= 0) {
        return (Clay_Dimensions){ 0, 0 };
    }
    size_t copy_len = (size_t)text.length < 4095 ? (size_t)text.length : 4095;
    char buf[4096];
    memcpy(buf, text.chars, copy_len);
    buf[copy_len] = '\0';

    FS_TextMetrics metrics = {0};
    float font_size = (float)(config ? config->fontSize : 14);
    if (!fs_measure_text_utf8(g_measure_core, font_size, buf, 0.0f, &metrics)) {
        float w = (float)text.length * font_size * 0.6f;
        return (Clay_Dimensions){ w, font_size };
    }
    return (Clay_Dimensions){
        metrics.width,
        metrics.em_height_ascent + metrics.em_height_descent
    };
}

static void clay_error_handler(Clay_ErrorData error) {
    fprintf(stderr, "Clay error type=%d: %.*s\n",
        (int)error.errorType,
        (int)error.errorText.length,
        error.errorText.chars ? error.errorText.chars : "");
    fflush(stderr);
}

/* ═══════════════════════════════════════════════════════════════════════════
   Chart drawing — smooth bezier line + area fill
   ═══════════════════════════════════════════════════════════════════════════ */

typedef struct ChartPoint {
    float x, y;
} ChartPoint;

static void draw_chart(
    FS_Core* core,
    float bx, float by, float bw, float bh,
    const ChartPoint* pts, size_t n,
    uint32_t line_color, uint32_t fill_color, uint32_t dot_color
) {
    if (!core || n < 2 || bw <= 0.0f || bh <= 0.0f) return;

    float min_x = pts[0].x, max_x = pts[0].x;
    float min_y = pts[0].y, max_y = pts[0].y;
    for (size_t i = 1; i < n; i++) {
        if (pts[i].x < min_x) min_x = pts[i].x;
        if (pts[i].x > max_x) max_x = pts[i].x;
        if (pts[i].y < min_y) min_y = pts[i].y;
        if (pts[i].y > max_y) max_y = pts[i].y;
    }
    float rx = max_x - min_x; if (rx <= 0) rx = 1;
    float ry = max_y - min_y; if (ry <= 0) ry = 1;

    float pad = 4.0f;
    float ix = bx + pad, iy = by + pad;
    float iw = bw - pad * 2.0f, ih = bh - pad * 2.0f;

    float sx[16], sy[16];
    size_t cnt = n < 16 ? n : 16;
    for (size_t i = 0; i < cnt; i++) {
        sx[i] = ix + ((pts[i].x - min_x) / rx) * iw;
        sy[i] = iy + (1.0f - (pts[i].y - min_y) / ry) * ih;
    }

    /* Area fill */
    FS_Path2D* fill = fs_path2d_create();
    if (fill) {
        fs_path2d_move_to(fill, sx[0], iy + ih);
        fs_path2d_line_to(fill, sx[0], sy[0]);
        for (size_t i = 1; i < cnt; i++) {
            float mx = (sx[i] + sx[i-1]) * 0.5f;
            float my = (sy[i] + sy[i-1]) * 0.5f;
            fs_path2d_quadratic_curve_to(fill, mx, my, sx[i], sy[i]);
        }
        fs_path2d_line_to(fill, sx[cnt-1], iy + ih);
        fs_path2d_close(fill);
        fs_path_fill_path2d(core, fill, fill_color);
        fs_path2d_destroy(fill);
    }

    /* Line */
    FS_Path2D* line = fs_path2d_create();
    if (line) {
        fs_path2d_move_to(line, sx[0], sy[0]);
        for (size_t i = 1; i < cnt; i++) {
            float mx = (sx[i] + sx[i-1]) * 0.5f;
            float my = (sy[i] + sy[i-1]) * 0.5f;
            fs_path2d_quadratic_curve_to(line, mx, my, sx[i], sy[i]);
        }
        fs_path_stroke_path2d(core, line, 2.0f, line_color);
        fs_path2d_destroy(line);
    }

    /* Dots */
    for (size_t i = 0; i < cnt; i++) {
        fs_cmd_circle(core, sx[i], sy[i], 3.0f, dot_color);
    }
}

/* ═══════════════════════════════════════════════════════════════════════════
   Helper: make a Clay_String from a C string (for dynamic strings)
   ═══════════════════════════════════════════════════════════════════════════ */

static inline Clay_String make_string(const char* s) {
    return (Clay_String){ .isStaticallyAllocated = false, .length = (int32_t)strlen(s), .chars = s };
}

